# ========== Упражнение 1. Прибыль / убыток / безубыточность ==========
# Спрашиваем у пользователя число (прибыль за месяц)
money = float(input("Введите прибыль за месяц (руб.): "))

# Если число больше нуля
if money > 0:
    print("Прибыль")
# Если число меньше нуля
