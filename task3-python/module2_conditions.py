# ========== Упражнение 2. Категория бизнеса ==========
# Спрашиваем годовую выручку
income = float(input("Введите годовую выручку (руб.): "))

# Проверяем по порогам
if income < 1000000:           # меньше 1 миллиона
    print("Микробизнес")
elif income < 10000000:        # от 1 до 10 миллионов
    print("Малый бизнес")
elif income < 100000000:       # от 10 до 100 миллионов
    print("Средний бизнес")
else:                          # 100 миллионов и больше
    print("Крупный бизнес")

print()

# ========== Упражнение 3. Расчёт НДФЛ ==========
# Спрашиваем зарплату до вычета налога
salary = float(input("Введите зарплату до налога (руб.): "))

# Выбираем ставку налога
if salary <= 50000:      # если зарплата до 50 000 рублей
    ndfl_rate = 0.13     # ставка 13%
else:                    # если больше 50 000
    ndfl_rate = 0.15     # ставка 15%

# Считаем налог
tax = salary * ndfl_rate

# Считаем сколько получит сотрудник на руки
after_tax = salary - tax

# Выводим результаты (два знака после запятой)
print("Налог:", tax, "руб.")
print("На руки:", after_tax, "руб.")

print()

# ========== Упражнение 4. Таблица умножения ставки ==========
# Спрашиваем процентную ставку (например, 5 или 7.5)
rate = float(input("Введите процентную ставку: "))

print("Таблица умножения:")
# Цикл от 1 до 12 (включительно)
for multiplier in range(1, 13):
    result = rate * multiplier
    print(rate, "×", multiplier, "=", result)

print()

