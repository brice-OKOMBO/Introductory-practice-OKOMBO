# ========== Упражнение 6. Рост вклада по годам ==========
# Спрашиваем начальную сумму
start_money = float(input("Сколько кладёте в банк (руб.): "))
# Спрашиваем годовой процент
percent = float(input("Годовой процент: "))

# Коэффициент роста: например, 5% -> 1.05
factor = 1 + percent / 100

# Текущая сумма в начале
current = start_money

print("Сумма в конце каждого года:")
# Цикл на 5 лет
for year in range(1, 6):
    current = current * factor    # прибавляем проценты
    print(year, "год:", current, "руб.")

print()

# ========== Упражнение 7. Накопительный счёт ==========
# Ежемесячный взнос
monthly_deposit = float(input("Сколько откладываете каждый месяц (руб.): "))
# Количество месяцев
months = int(input("На сколько месяцев: "))

total_money = 0   # накопленная сумма (сначала 0)
print("Накопления по месяцам:")
for month in range(1, months + 1):
    total_money = total_money + monthly_deposit   # добавляем взнос
    print("Месяц", month, ":", total_money, "руб.")

print()

# ========== Упражнение 8. Доступность товаров ==========
# Бюджет покупателя
budget = float(input("Ваш бюджет (руб.): "))

# Список товаров и их цены
products = ["Хлеб", "Молоко", "Сыр", "Колбаса", "Печенье"]
costs = [40, 70, 350, 500, 80]

print("Проверка доступности:")
# Проходим по всем товарам
for i in range(len(products)):
    name = products[i]      # название
    price = costs[i]        # цена
    if budget >= price:
        print(name, "— доступен")
    else:
        # Сколько не хватает
        shortage = price - budget
        print(name, "— не хватает", shortage, "руб.")

print()

# ========== Упражнение 9. Выручка за полгода ==========
# Создаём пустой список для выручки по месяцам
revenues = []

print("Введите выручку за 6 месяцев:")
for month in range(1, 7):
    rev = float(input("Месяц " + str(month) + ": "))
    revenues.append(rev)    # добавляем в список

# Находим минимальное, максимальное и среднее
min_rev = min(revenues)
max_rev = max(revenues)
avg_rev = sum(revenues) / 6

print("Минимальная выручка:", min_rev, "руб.")
print("Максимальная выручка:", max_rev, "руб.")
print("Средняя выручка:", avg_rev, "руб.")

print()

# ========== Упражнение 10. Анализ рентабельности ==========
# Порог рентабельности (в процентах)
threshold = float(input("Введите пороговую рентабельность (%): "))

# Список для хранения рентабельности за 6 месяцев
profitability = []

print("Введите рентабельность за каждый месяц (%):")
for month in range(1, 7):
    value = float(input("Месяц " + str(month) + ": "))
    profitability.append(value)

# Считаем, сколько месяцев выше порога
count = 0
for value in profitability:
    if value > threshold:
        count = count + 1

print("Месяцев выше порога:", count)